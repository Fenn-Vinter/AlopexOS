    inline const fennlib::u8* char_to_font(char c) {
        if (c >= 'A' && c <= 'Z') {
            return font_8x8[c - 'A'];
        } else if (c >= 'a' && c <= 'z') {
            return font_8x8[c - 'a'];
        } else if (c >= '0' && c <= '9') {
            return font_8x8[(c - '0') + 26];
        } else if (c == ' ') {
            return font_8x8[36];
        } else if (c == '_') {
            return font_8x8[37];
        } else if (c == '.') {
            return font_8x8[38];
        } else if (c == '?') {
            return font_8x8[39];
        } else if (c == '!') {
            return font_8x8[40];
        } else if (c == ',') {
            return font_8x8[41];
        } else if (c == '=') {
            return font_8x8[42];
        } else if (c == '-') {
            return font_8x8[43];
        } else if (c == '"') {
            return font_8x8[44];
        } else if (c == ':') {
            return font_8x8[45];
        } else if (c == '(') {
            return font_8x8[46];
        } else if (c == ')') {
            return font_8x8[47];
        }

        return font_8x8[36];
    }
